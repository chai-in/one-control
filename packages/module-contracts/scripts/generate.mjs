import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const schemaPath = new URL("../schema/wire.json", import.meta.url);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const goNames = {
  id: "ID",
  deviceId: "DeviceID",
  enrollmentId: "EnrollmentID",
  keyId: "KeyID",
  machineId: "MachineID",
  sessionId: "SessionID",
  url: "URL",
  sha256: "SHA256",
  archiveSha256: "ArchiveSHA256",
  schemaVersion: "SchemaVersion",
  authorityEpoch: "AuthorityEpoch",
};
const name = (key) => goNames[key] ?? key[0].toUpperCase() + key.slice(1);
function type(kind, language) {
  if (kind.startsWith("array:"))
    return language === "go" ? `[]${type(kind.slice(6), language)}` : `${type(kind.slice(6), language)}[]`;
  if (kind.startsWith("map:") || kind.startsWith("platformmap:"))
    return language === "go"
      ? `map[string]${type(kind.slice(kind.indexOf(":") + 1), language)}`
      : `Record<string, ${type(kind.slice(kind.indexOf(":") + 1), language)}>`;
  if (schema.types[kind]) return kind;
  if (kind === "boolean") return language === "go" ? "bool" : "boolean";
  if (["timestamp", "size"].includes(kind) || /^literal:[0-9]+$/.test(kind))
    return language === "go" ? "int64" : kind.startsWith("literal:") ? kind.slice(8) : "number";
  if (language === "ts" && kind.startsWith("literal:")) return JSON.stringify(kind.slice(8));
  if (language === "ts" && kind.startsWith("enum:"))
    return kind.slice(5).split(",").map(JSON.stringify).join(" | ");
  return "string";
}
let go =
  "// Code generated by packages/module-contracts/scripts/generate.mjs; DO NOT EDIT.\npackage contracts\n\n";
let ts = "// Code generated from schema/wire.json; DO NOT EDIT.\n";
for (const [model, fields] of Object.entries(schema.types)) {
  go += `type ${model} struct {\n`;
  ts += `export interface ${model} {\n`;
  for (const [raw, kind] of Object.entries(fields)) {
    const optional = raw.endsWith("?");
    const key = raw.replace(/\?$/, "");
    let gt = type(kind, "go");
    if (optional && !gt.startsWith("[]") && !gt.startsWith("map[")) gt = `*${gt}`;
    go += `\t${name(key)} ${gt} \`json:"${key}${optional ? ",omitempty" : ""}"\`\n`;
    ts += `  ${key}${optional ? "?" : ""}: ${type(kind, "ts")};\n`;
  }
  go += "}\n\n";
  ts += "}\n";
}
ts += `export interface WireModels {\n${Object.keys(schema.types)
  .map((model) => `  ${model}: ${model};`)
  .join("\n")}\n}\n`;
go += `const SchemaJSON = ${JSON.stringify(JSON.stringify(schema))}\n`;
ts += `export const wireSchema = ${JSON.stringify(schema, null, 2)} as const;\n`;
const formatted = spawnSync(
  process.execPath,
  [
    fileURLToPath(new URL("../../../node_modules/@biomejs/biome/bin/biome", import.meta.url)),
    "format",
    "--stdin-file-path=wire.generated.ts",
  ],
  { input: ts, encoding: "utf8" },
);
if (formatted.status !== 0) throw new Error(`Biome formatter failed: ${formatted.stderr}`);
ts = formatted.stdout;
const outputs = [
  [new URL("../../../native/internal/contracts/wire_generated.go", import.meta.url), go],
  [new URL("../src/wire.generated.ts", import.meta.url), ts],
];
const removeLayoutOutsideQuotedLiterals = (source) =>
  source.replace(/"(?:\\.|[^"\\])*"|`[^`]*`|(\s+)/g, (match, space) => (space ? "" : match));
for (const [url, content] of outputs) {
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = await readFile(url, "utf8");
    } catch {}
    if (url.pathname.endsWith(".go")) {
      if (removeLayoutOutsideQuotedLiterals(actual) !== removeLayoutOutsideQuotedLiterals(content))
        throw new Error(`Generated file drift: ${fileURLToPath(url)}`);
    } else if (actual !== content) throw new Error(`Generated file drift: ${fileURLToPath(url)}`);
  } else await writeFile(url, content);
}
